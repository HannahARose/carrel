//! The comments a slicer writes in G-code: the program, printer, filament, layer height,
//! print time and the objects printed. `PrusaSlicer` and Bambu Studio write most of them as
//! `; key = value`, at the start or the end; Cura as `;KEY:value` at the start.

use std::fmt::Write as _;
use std::io::{Read, Seek, SeekFrom};
use std::path::Path;

use super::{Details, date, push_unique};

/// How much of the start, and of the end, is read, in bytes.
const SPAN: u64 = 256 * 1024;

pub(super) fn read(path: &Path) -> std::io::Result<Details> {
    let mut file = std::fs::File::open(path)?;
    let length = file.metadata()?.len();
    let mut text = Vec::new();
    (&mut file).take(SPAN).read_to_end(&mut text)?;
    if length > SPAN * 2 {
        file.seek(SeekFrom::Start(length - SPAN))?;
        text.push(b'\n');
    }
    if length > SPAN {
        file.read_to_end(&mut text)?;
    }
    Ok(details(&String::from_utf8_lossy(&text)))
}

/// What the comments in `text` say.
pub(super) fn details(text: &str) -> Details {
    let mut values: Vec<(String, String)> = Vec::new();
    let mut objects = Vec::new();
    let mut generator = None;
    for line in text.lines() {
        let line = line.trim();
        if let Some(name) = object(line) {
            push_unique(&mut objects, &name);
        }
        let Some(comment) = line.strip_prefix(';') else {
            continue;
        };
        let comment = comment.trim();
        if generator.is_none() {
            generator = program(comment);
        }
        let pair = comment
            .split_once(" = ")
            .or_else(|| comment.split_once(':'));
        if let Some((key, value)) = pair {
            let key = key.trim().to_ascii_lowercase();
            if !values.iter().any(|(k, _)| *k == key) {
                values.push((key, value.trim().trim_matches('"').to_owned()));
            }
        }
    }
    let get = |keys: &[&str]| {
        keys.iter()
            .find_map(|k| values.iter().find(|(key, _)| key == k))
            .map(|(_, v)| v.clone())
            .unwrap_or_default()
    };
    let mut details = Details::new("G-code for a 3D printer");
    let mut created = None;
    if let Some(generator) = &generator {
        // `PrusaSlicer 2.7.1 on 2024-03-01 at 10:00:00 UTC`: the program, and when.
        let (program, when) = generator
            .split_once(" on ")
            .map_or((generator.as_str(), None), |(p, w)| (p, Some(w)));
        details.heading = format!("G-code for a 3D printer, from {}", program.trim());
        created = when.and_then(date);
    }
    details.created = created;
    details.add(
        "Printer",
        get(&[
            "printer_settings_id",
            "printer_model",
            "target_machine.name",
            "machine_name",
        ]),
    );
    details.add("Filament", filament(&get));
    let layer = get(&["layer_height", "layer height"]);
    if !layer.is_empty() {
        details.add("Layer height", format!("{layer} mm"));
    }
    details.add("Print time", print_time(&get));
    details.add_names("Objects", &objects);
    details
}

/// The slicer that wrote a comment such as `generated by PrusaSlicer 2.7.1 on …`,
/// `Generated with Cura_SteamEngine 5.6.0`, or Bambu Studio's `BambuStudio 02.07.01.62`.
fn program(comment: &str) -> Option<String> {
    let lower = comment.to_ascii_lowercase();
    if let Some(prefix) = ["generated by ", "generated with "]
        .iter()
        .find(|p| lower.starts_with(*p))
    {
        return Some(comment[prefix.len()..].trim().to_owned());
    }
    let mut words = comment.split_whitespace();
    let (name, version) = (words.next()?, words.next()?);
    let slicer = ["BambuStudio", "OrcaSlicer", "PrusaSlicer", "SuperSlicer"]
        .iter()
        .any(|s| name.eq_ignore_ascii_case(s));
    (slicer && words.next().is_none() && version.starts_with(|c: char| c.is_ascii_digit()))
        .then(|| comment.to_owned())
}

/// The filament's name, or its type when it has none, such as `Prusament PLA`, and how much,
/// when said. The name comes first: Bambu Studio's type can be another slot's.
fn filament(get: &dyn Fn(&[&str]) -> String) -> String {
    let first = |value: String| {
        value
            .split(';')
            .next()
            .unwrap_or_default()
            .trim()
            .to_owned()
    };
    let name = first(get(&["filament_settings_id"]));
    let mut text = if name.is_empty() {
        first(get(&["filament_type", "material"]))
    } else {
        name
    };
    let grams = get(&["filament used [g]", "total filament weight [g]"]);
    if !grams.is_empty() && grams != "0" && grams != "0.00" {
        write!(text, ", {grams} g").unwrap();
    }
    text
}

/// How long it takes: the slicer's own words, or Cura's seconds as hours and minutes.
fn print_time(get: &dyn Fn(&[&str]) -> String) -> String {
    let said = get(&[
        "estimated printing time (normal mode)",
        "total estimated time",
        "model printing time",
    ]);
    if !said.is_empty() {
        return said.split(';').next().unwrap_or_default().trim().to_owned();
    }
    get(&["time"])
        .parse::<u64>()
        .map_or_else(|_| String::new(), super::duration)
}

/// The name of an object printed, from the ways slicers label them.
fn object(line: &str) -> Option<String> {
    if let Some(name) = line.strip_prefix("; printing object ") {
        // PrusaSlicer: `; printing object Shape-Box id:0 copy 0`.
        let name = name.split(" id:").next().unwrap_or(name);
        return Some(name.trim().to_owned());
    }
    if let Some(name) = line.strip_prefix(";MESH:") {
        return (name != "NONMESH").then(|| name.trim().to_owned());
    }
    if let Some(rest) = line.strip_prefix("EXCLUDE_OBJECT_DEFINE NAME=") {
        return Some(
            rest.split_whitespace()
                .next()?
                .trim_matches('\'')
                .to_owned(),
        );
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn prusaslicer_comments_are_read_from_the_start_and_end() {
        let text = "; generated by PrusaSlicer 2.7.1 on 2024-03-01 at 10:00:00 UTC
G28
; printing object bracket.stl id:0 copy 0
G1 X10 Y10
; stop printing object bracket.stl id:0 copy 0
; printing object bracket.stl id:0 copy 1
; filament used [g] = 12.34
; estimated printing time (normal mode) = 1h 2m 3s
; filament_settings_id = \"Prusament PLA\"
; filament_type = PLA
; layer_height = 0.2
; printer_settings_id = Original Prusa MK4 0.4 nozzle
";
        let details = details(text);
        assert_eq!(
            details.text(),
            "G-code for a 3D printer, from PrusaSlicer 2.7.1
Printer: Original Prusa MK4 0.4 nozzle
Filament: Prusament PLA, 12.34 g
Layer height: 0.2 mm
Print time: 1h 2m 3s
Objects: bracket.stl"
        );
        assert_eq!(details.created.as_deref(), Some("2024-03-01"));
    }

    #[test]
    fn bambu_studio_names_itself_on_its_own_line() {
        let text = "; HEADER_BLOCK_START
; BambuStudio 02.07.01.62
; model printing time: 1h 14m 53s; total estimated time: 1h 14m 54s
; total filament weight [g] : 0.00
; HEADER_BLOCK_END
; filament_settings_id = \"Generic PETG @BBL P2S\"
; filament_type = PLA
; printer_model = Bambu Lab P2S
";
        assert_eq!(
            details(text).text(),
            "G-code for a 3D printer, from BambuStudio 02.07.01.62
Printer: Bambu Lab P2S
Filament: Generic PETG @BBL P2S
Print time: 1h 14m 53s"
        );
    }

    #[test]
    fn cura_comments_are_read() {
        let text = ";FLAVOR:Marlin
;TIME:5430
;Filament used: 1.5m
;Layer height: 0.12
;MESH:ring.stl
G1 X1
;MESH:NONMESH
;TARGET_MACHINE.NAME:Creality Ender-3
;Generated with Cura_SteamEngine 5.6.0
";
        assert_eq!(
            details(text).text(),
            "G-code for a 3D printer, from Cura_SteamEngine 5.6.0
Printer: Creality Ender-3
Layer height: 0.12 mm
Print time: 1h 30m
Objects: ring.stl"
        );
    }

    #[test]
    fn long_files_are_read_at_both_ends_only() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("print.gcode");
        let mut text = String::from("; generated by OrcaSlicer 2.1.0\n");
        text.push_str(&"G1 X1 Y1 ; layer_height = 9\n".repeat(60_000));
        text.push_str("; layer_height = 0.16\n");
        std::fs::write(&path, text).unwrap();
        let details = read(&path).unwrap();
        assert!(
            details.text().ends_with("Layer height: 0.16 mm"),
            "{}",
            details.text()
        );
    }
}
